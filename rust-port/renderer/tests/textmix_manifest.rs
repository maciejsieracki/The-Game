//! RR-T8f fixtures guard (R-RUSTPORT-P4-35-TEXT-EMOJI-UNIFY-Q1): every file
//! of `tests/fixtures/textmix/` written by `gen.mjs` (and the bundled fonts
//! it loaded) matches `MANIFEST.sha256`, every fixture file is listed, and
//! the fixture stays within the 4 MB allowlist budget. SHA-256 is the
//! FIPS 180-4 routine of `tests/cityoverlay_web_parity.rs` (no new
//! dependency).

use std::fmt::Write as _;

fn fx_path(rel: &str) -> String {
    format!(
        "{}/tests/fixtures/textmix/{rel}",
        env!("CARGO_MANIFEST_DIR")
    )
}

fn sha256(data: &[u8]) -> [u8; 32] {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4,
        0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe,
        0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f,
        0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
        0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc,
        0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
        0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116,
        0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];
    let mut msg = data.to_vec();
    let bit_len = (data.len() as u64).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&bit_len.to_be_bytes());
    for chunk in msg.chunks(64) {
        let mut w = [0u32; 64];
        for (i, word) in chunk.chunks(4).enumerate() {
            w[i] = u32::from_be_bytes([word[0], word[1], word[2], word[3]]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let mut v = h;
        for i in 0..64 {
            let s1 = v[4].rotate_right(6) ^ v[4].rotate_right(11) ^ v[4].rotate_right(25);
            let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
            let t1 = v[7]
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K[i])
                .wrapping_add(w[i]);
            let s0 = v[0].rotate_right(2) ^ v[0].rotate_right(13) ^ v[0].rotate_right(22);
            let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
            let t2 = s0.wrapping_add(maj);
            v[7] = v[6];
            v[6] = v[5];
            v[5] = v[4];
            v[4] = v[3].wrapping_add(t1);
            v[3] = v[2];
            v[2] = v[1];
            v[1] = v[0];
            v[0] = t1.wrapping_add(t2);
        }
        for (a, b) in h.iter_mut().zip(v) {
            *a = a.wrapping_add(b);
        }
    }
    let mut out = [0u8; 32];
    for (i, x) in h.iter().enumerate() {
        out[i * 4..i * 4 + 4].copy_from_slice(&x.to_be_bytes());
    }
    out
}

fn hex(b: &[u8]) -> String {
    b.iter().fold(String::new(), |mut s, x| {
        let _ = write!(s, "{x:02x}");
        s
    })
}

#[test]
fn sha256_matches_standard_vectors() {
    assert_eq!(
        hex(&sha256(b"abc")),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    assert_eq!(
        hex(&sha256(b"")),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
}

#[test]
fn textmix_fixtures_match_manifest_sha256() {
    let man = std::fs::read_to_string(fx_path("MANIFEST.sha256")).expect("manifest");
    let mut listed = std::collections::BTreeSet::new();
    let mut total = 0usize;
    for line in man.lines() {
        let (want, file) = line.split_once("  ").expect("sha256  file");
        let bytes = std::fs::read(fx_path(file)).unwrap_or_else(|e| panic!("{file}: {e}"));
        assert_eq!(hex(&sha256(&bytes)), want, "{file}");
        if !file.starts_with("../") {
            total += bytes.len();
            listed.insert(file.to_owned());
        }
    }
    // Every generated file is listed (golden.tsv / MANIFEST.sha256 are
    // written by the Rust test / the generator itself).
    let mut on_disk = std::collections::BTreeSet::new();
    for dir in ["", "ref/"] {
        for e in std::fs::read_dir(fx_path(dir)).expect("dir") {
            let e = e.expect("entry");
            if e.file_type().expect("type").is_file() {
                let name = format!("{dir}{}", e.file_name().to_string_lossy());
                if name != "MANIFEST.sha256" && name != "golden.tsv" {
                    on_disk.insert(name);
                }
            }
        }
    }
    assert_eq!(
        listed, on_disk,
        "MANIFEST lists exactly the generated files"
    );
    assert!(total <= 4 << 20, "fixture {total} B > 4 MB");
    println!("textmix fixture: {} files, {total} B", listed.len());
}
